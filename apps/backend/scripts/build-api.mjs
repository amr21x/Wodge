import { mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const backend = fileURLToPath(new URL("../", import.meta.url));
const config = ts.readConfigFile(
  path.join(backend, "tsconfig.json"),
  ts.sys.readFile,
);
if (config.error)
  throw new Error(
    ts.flattenDiagnosticMessageText(config.error.messageText, "\n"),
  );
const parsed = ts.parseJsonConfigFileContent(
  config.config,
  ts.sys,
  backend,
  {},
  path.join(backend, "tsconfig.json"),
);
const entry = path.join(backend, "src/types/api-types.ts");
/** @param {ts.Program} program */
async function generate(program) {
  const diagnostics = ts.getPreEmitDiagnostics(program);
  if (diagnostics.length) {
    console.error(
      ts.formatDiagnosticsWithColorAndContext(diagnostics, {
        getCanonicalFileName: (name) => name,
        getCurrentDirectory: () => backend,
        getNewLine: () => "\n",
      }),
    );
    process.exitCode = 1;
  } else {
    const checker = program.getTypeChecker();
    const source = program.getSourceFile(entry);
    if (!source) throw new Error("Missing API contract source");
    const api = source.statements
      .filter(ts.isTypeAliasDeclaration)
      .find((node) => node.name.text === "ApiType");
    if (!api || !ts.isTypeReferenceNode(api.type))
      throw new Error("Missing public ApiType");
    const schemaNode = api.type.typeArguments?.[1];
    if (!schemaNode) throw new Error("Missing API schema");
    const schema = checker.getTypeFromTypeNode(schemaNode);
    const honoTypes = await realpath(
      path.join(backend, "node_modules/hono/dist/types"),
    );
    const flags =
      ts.TypeFormatFlags.NoTruncation |
      ts.TypeFormatFlags.InTypeAlias |
      ts.TypeFormatFlags.UseFullyQualifiedType;
    // Resolve the HTTP schema structurally. Normal declaration emission would retain
    // references to route classes and transitively expose the server's dependency graph.
    const routes = checker.getPropertiesOfType(schema).map((route) => {
      const endpoint = checker.typeToString(
        checker.getTypeOfSymbolAtLocation(route, source),
        undefined,
        flags,
      );
      const portable = endpoint.replace(/import\("([^"]+)"\)/g, (_, module) => {
        const relative = path
          .relative(honoTypes, module)
          .replaceAll(path.sep, "/");
        if (relative.startsWith("..") || path.isAbsolute(relative)) {
          throw new Error(
            `Non-public type leaked into the API contract: ${module}`,
          );
        }
        return `import("hono/${relative}")`;
      });
      return `  ${JSON.stringify(route.name)}: ${portable};`;
    });
    if (!routes.length) throw new Error("The public API schema is empty");
    const declaration = `// Generated by build:api from the actual Hono route tree. Do not edit.\nimport type { Hono } from "hono";\n\nexport type ApiType = Hono<{}, {\n${routes.join("\n")}\n}>;\n`;
    await mkdir(path.join(backend, "dist"), { recursive: true });
    const output = path.join(backend, "dist/api-types.d.ts");
    let previous;
    try {
      previous = await readFile(output, "utf8");
    } catch (error) {
      if (
        !(error instanceof Error) ||
        !("code" in error) ||
        error.code !== "ENOENT"
      )
        throw error;
    }
    if (previous !== declaration) await writeFile(output, declaration);
    process.exitCode = 0;
    console.log(`Generated public contract for ${routes.length} route paths`);
  }
}

if (process.argv.includes("--watch")) {
  const host = ts.createWatchCompilerHost(
    [entry],
    { ...parsed.options, incremental: false },
    ts.sys,
    ts.createSemanticDiagnosticsBuilderProgram,
  );
  host.afterProgramCreate = (builder) => {
    void generate(builder.getProgram()).catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
  };
  ts.createWatchProgram(host);
} else {
  await generate(
    ts.createProgram([entry], { ...parsed.options, incremental: false }),
  );
}
